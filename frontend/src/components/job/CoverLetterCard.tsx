import { useEffect, useState } from "react";
import { Link } from "react-router-dom";

import type { ApiError } from "../../api/errors";
import type { CoverLetterEnvelope } from "../../types/api";
import { formatPercent } from "../../utils/format";
import { mentionsMatch, mentionsResume } from "../../utils/errorHints";
import { Badge } from "../ui/Badge";
import { Button } from "../ui/Button";
import { Card, CardBody, CardHeader } from "../ui/Card";
import { ErrorAlert } from "../ui/ErrorAlert";
import { EmptyState, LoadingState } from "../ui/EmptyState";
import { Icon } from "../ui/Icon";

export function CoverLetterCard({
  envelope,
  pending,
  error,
  onGenerate,
  onMatch,
}: {
  envelope: CoverLetterEnvelope | null;
  pending: boolean;
  error: ApiError | null;
  onGenerate: () => void;
  onMatch: () => void;
}) {
  const [copied, setCopied] = useState(false);
  const [copyError, setCopyError] = useState<string | null>(null);

  useEffect(() => {
    if (!copied) {
      return undefined;
    }
    const timer = window.setTimeout(() => setCopied(false), 2000);
    return () => window.clearTimeout(timer);
  }, [copied]);

  async function handleCopy() {
    if (!envelope) {
      return;
    }
    try {
      await navigator.clipboard.writeText(envelope.cover_letter.content);
      setCopyError(null);
      setCopied(true);
    } catch {
      setCopyError("Copying failed here — select the text and copy it manually.");
    }
  }

  return (
    <Card id="cover-letter">
      <CardHeader
        title="Cover letter"
        description="Written from your job analysis, match and master resume."
        actions={
          envelope ? (
            <Badge tone="info">
              Confidence {formatPercent(envelope.cover_letter.confidence)}
            </Badge>
          ) : null
        }
      />
      <CardBody>
        {pending ? (
          <LoadingState message="Writing your cover letter…" />
        ) : error ? (
          <ErrorAlert
            message={error.message}
            action={
              mentionsMatch(error) ? (
                <Button size="sm" variant="secondary" onClick={onMatch}>
                  Match this job first
                </Button>
              ) : mentionsResume(error) ? (
                <Link
                  to="/resume"
                  className="inline-flex items-center rounded-lg bg-white px-3 py-1.5 text-xs font-medium text-rose-700 ring-1 ring-inset ring-rose-200 hover:bg-rose-50"
                >
                  Upload your resume
                </Link>
              ) : (
                <Button size="sm" variant="secondary" onClick={onGenerate}>
                  Retry
                </Button>
              )
            }
          />
        ) : envelope ? (
          <div className="space-y-4">
            {copyError ? <ErrorAlert message={copyError} /> : null}
            <div className="rounded-xl border border-slate-200 bg-white p-5">
              <p className="whitespace-pre-wrap text-sm leading-7 text-slate-800">
                {envelope.cover_letter.content}
              </p>
            </div>
            <div className="flex flex-wrap items-center justify-between gap-3">
              <p className="text-xs text-slate-500">
                Generated by the copilot — copy it into your application. Nothing is
                sent anywhere automatically.
              </p>
              <Button variant="secondary" size="sm" onClick={() => void handleCopy()}>
                <Icon name={copied ? "check" : "copy"} className="h-4 w-4" />
                {copied ? "Copied" : "Copy letter"}
              </Button>
            </div>
          </div>
        ) : (
          <EmptyState
            compact
            title="Generate a cover letter"
            description="The letter is grounded in the stored match and your uploaded resume. If one already exists for this match, the stored letter is returned."
            action={
              <Button onClick={onGenerate} loading={pending}>
                Generate cover letter
              </Button>
            }
          />
        )}
      </CardBody>
    </Card>
  );
}
